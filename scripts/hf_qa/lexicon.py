SPECIES_FLAT: list[str] = [s for terms in SPECIES.values() for s in terms]
ALL_TOPIC_TERMS: dict[str, set[str]] = {k: set(v) for k, v in TOPIC_TERMS.items()}


def hits(text: str, terms) -> list[str]:
    low = text.lower()
    return [t for t in terms if t.lower() in low]


def classify(text: str) -> dict:
    """Rule verdict for one QA (question + answer concatenated)."""
    sp = hits(text, SPECIES_FLAT)
    aqua = hits(text, AQUA_TERMS)
    strong = hits(text, STRONG_TERMS)
    excluded = hits(text, EXCLUDE_TERMS)
    topics = {k: hits(text, terms) for k, terms in ALL_TOPIC_TERMS.items()}
    active_topics = sorted(k for k, v in topics.items() if v)

    species_hit = bool(sp)
    context_hit = bool(aqua)
    strong_hit = bool(strong)
    is_aqua = (species_hit and (context_hit or strong_hit)) or (
        strong_hit and not excluded
    ) or (species_hit and not excluded and any(topics.values()))
    return {
        "is_aquaculture_rule": is_aqua,
        "species_hits": sp,
        "aqua_context_hits": aqua,
        "strong_hits": strong,
        "exclude_hits": excluded,
        "topics": active_topics,
        "topic_terms": {k: v for k, v in topics.items() if v},
    }


